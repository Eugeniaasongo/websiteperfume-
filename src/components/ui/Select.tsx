import React from 'react';
import { clsx } from 'clsx';
import { twMerge } from 'tailwind-merge';

export interface SelectProps extends React.SelectHTMLAttributes<HTMLSelectElement> {
  label?: string;
  error?: string;
  options: { label: string; value: string | number }[];
}

export const Select = React.forwardRef<HTMLSelectElement, SelectProps>(
  ({ className, label, error, options, id, ...props }, ref) => {
    const selectId = id || (label ? label.toLowerCase().replace(/\s+/g, '-') : undefined);

    return (
      <div className="w-full flex flex-col space-y-1.5">
        {label && (
          <label htmlFor={selectId} className="text-xs font-semibold tracking-wider uppercase text-charcoal">
            {label}
          </label>
        )}
        <select
          id={selectId}
          ref={ref}
          className={twMerge(
            clsx(
              'w-full px-4 py-2.5 text-sm bg-paper border border-charcoal/20 text-ink transition-colors duration-200 focus:outline-none focus:border-gold focus:ring-1 focus:ring-gold disabled:bg-paper-soft disabled:cursor-not-allowed',
              error && 'border-alert-red focus:border-alert-red focus:ring-alert-red',
              className
            )
          )}
          {...props}
        >
          {options.map((opt) => (
            <option key={opt.value} value={opt.value}>
              {opt.label}
            </option>
          ))}
        </select>
        {error && <p className="text-xs text-alert-red mt-0.5">{error}</p>}
      </div>
    );
  }
);

Select.displayName = 'Select';
